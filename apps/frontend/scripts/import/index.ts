// Dev-only importer: `npm run import`. Reads ../eras-clone (read-only) and writes src/data/{faq,
// posts,post-categories,listings,assets}.ts.
// Not run in CI (no source mirror there); CI guards the committed output instead.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { format, resolveConfig } from 'prettier';
import { crossCheck, importFAQs } from './faq.ts';
import type { Stats } from './html.ts';
import { importPosts } from './posts.ts';

const here = import.meta.dirname;
const ERAS_CLONE_DIR = path.resolve(
  process.env.ERAS_CLONE_DIR ?? path.join(here, '../../../../../eras-clone'),
);
const DOCS_DIR = path.resolve(process.env.DOCS_DIR ?? path.join(here, '../../../../docs'));
const DATA = path.resolve(here, '../../src/data');
const HEADER = '// Generated by scripts/import (npm run import) — do not edit.';

async function writeTs(file: string, body: string) {
  const options = await resolveConfig(file);
  const text = await format(body, { ...options, filepath: file });
  const changed = !existsSync(file) || readFileSync(file, 'utf8') !== text;
  if (changed) writeFileSync(file, text);
  console.log(`${changed ? 'wrote' : 'unchanged'} ${path.relative(process.cwd(), file)}`);
}

async function main() {
  if (!existsSync(path.join(ERAS_CLONE_DIR, 'index.html')))
    throw new Error(`Source mirror not found at ${ERAS_CLONE_DIR} (set ERAS_CLONE_DIR)`);
  const stats: Stats = { brand: 0, scrub: 0 };
  const { faqs, topics, occurrences } = importFAQs(ERAS_CLONE_DIR, stats);
  const checked = crossCheck(path.join(DOCS_DIR, 'evidence/faq-occurrences.json'), occurrences);
  console.log(
    `faq: ${checked} occurrences -> ${faqs.length} FAQs, ${topics.length} topics ` +
      `(${stats.scrub} contact scrubs, ${stats.brand} brand replacements)`,
  );
  await writeTs(
    path.join(DATA, 'faq.ts'),
    `${HEADER}
import type { FAQ, FAQTopic } from '@/types/content';

export const faqs: FAQ[] = ${JSON.stringify(faqs)};

export const faqTopics: FAQTopic[] = ${JSON.stringify(topics)};
`,
  );

  const postStats: Stats = { brand: 0, scrub: 0 };
  const { posts, categories, snapshots, assets } = importPosts(ERAS_CLONE_DIR, postStats);
  console.log(
    `posts: ${posts.length} posts, ${categories.length} categories, ${snapshots.length} listing ` +
      `pages, ${assets.length} assets (${assets.filter((a) => a.status === 'local').length} local) ` +
      `(${postStats.scrub} contact scrubs, ${postStats.brand} brand replacements)`,
  );
  await writeTs(
    path.join(DATA, 'posts.ts'),
    `${HEADER}
import type { Post } from '@/types/content';

export const posts: Post[] = ${JSON.stringify(posts)};
`,
  );
  await writeTs(
    path.join(DATA, 'post-categories.ts'),
    `${HEADER}
import type { PostCategory, SourceRef } from '@/types/content';

export const postCategories: (PostCategory & { sources: SourceRef[] })[] = ${JSON.stringify(categories)};
`,
  );
  await writeTs(
    path.join(DATA, 'listings.ts'),
    `${HEADER}
import type { ListingSettings, ListingSnapshot } from '@/types/content';

export const listingSettings: ListingSettings[] = [];
export const listingSnapshots: ListingSnapshot[] = ${JSON.stringify(snapshots)};
`,
  );
  await writeTs(
    path.join(DATA, 'assets.ts'),
    `${HEADER}
import type { AssetRef } from '@/types/content';

export const assets: AssetRef[] = ${JSON.stringify(assets)};
`,
  );
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
